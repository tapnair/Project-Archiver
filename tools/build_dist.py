#!/usr/bin/env python3
"""Build the installable Project-Archiver distribution zip.

The zip is written to dist/ (git-ignored) and is meant to be attached to a
GitHub release, not committed:

    python tools/build_dist.py
    git tag v2.1.2
    git push origin v2.1.2
    gh release create v2.1.2 --title v2.1.2 --notes "..." dist/Project-Archiver-2.1.2.zip

The version is read from Project-Archiver/Project-Archiver.manifest, which is
what Fusion shows in the Add-Ins dialog. Bump it (and setup.py) before building.

The resulting archive mirrors the historical sdist layout:

    project_archiver-<version>/
        PKG-INFO, README.md, LICENSE, setup.py, setup.cfg
        Project_Archiver.egg-info/
        Project-Archiver/            <- the folder to select in Fusion
            Project-Archiver.py, startup.py, config.py, *.manifest
            apper/apper/             <- bundled dependency
            commands/, resources/
"""

import argparse
import json
import re
import shutil
import sys
import tempfile
import zipfile
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
ADDIN = REPO / 'Project-Archiver'
MANIFEST = ADDIN / 'Project-Archiver.manifest'
EGG_INFO = REPO / 'Project_Archiver.egg-info'

# Files that must be present in the finished archive.
REQUIRED_ENTRIES = (
    'Project-Archiver/Project-Archiver.py',
    'Project-Archiver/Project-Archiver.manifest',
    'Project-Archiver/startup.py',
    'Project-Archiver/config.py',
    'Project-Archiver/commands/ExportCommand.py',
    'Project-Archiver/apper/apper/__init__.py',
)


def read_version():
    with MANIFEST.open(encoding='utf-8') as handle:
        return json.load(handle)['version']


def check_sources(version):
    """Fail early on the problems that produce a broken distribution."""
    if not (ADDIN / 'apper' / 'apper' / '__init__.py').is_file():
        raise SystemExit(
            "error: the apper submodule is not checked out.\n"
            "       run: git submodule update --init --recursive"
        )

    setup_py = (REPO / 'setup.py').read_text(encoding='utf-8')
    match = re.search(r"version\s*=\s*'([^']+)'", setup_py)
    if match and match.group(1) != version:
        raise SystemExit(
            "error: version mismatch.\n"
            "       Project-Archiver.manifest: {}\n"
            "       setup.py:                  {}\n"
            "       update both before building.".format(version, match.group(1))
        )

    egg_pkg_info = EGG_INFO / 'PKG-INFO'
    if egg_pkg_info.is_file():
        match = re.search(r'^Version:\s*(\S+)', egg_pkg_info.read_text(encoding='utf-8'), re.MULTILINE)
        if match and match.group(1) != version:
            print('warning: Project_Archiver.egg-info/PKG-INFO says {}, manifest says {}'.format(
                match.group(1), version))


def copy(src, dst):
    dst.parent.mkdir(parents=True, exist_ok=True)
    shutil.copy2(str(src), str(dst))


def populate(stage, version):
    """Copy the files that belong in the distribution into `stage`."""
    for name in ('setup.py', 'README.md', 'LICENSE'):
        copy(REPO / name, stage / name)

    addin_out = stage / 'Project-Archiver'
    for path in ADDIN.glob('*.py'):
        copy(path, addin_out / path.name)
    for path in ADDIN.glob('*.manifest'):
        copy(path, addin_out / path.name)

    for folder in ('commands', 'resources'):
        for path in (ADDIN / folder).rglob('*'):
            if path.is_file() and '__pycache__' not in path.parts:
                copy(path, addin_out / path.relative_to(ADDIN))

    # Only the apper package itself, not its docs or .git file.
    for path in (ADDIN / 'apper' / 'apper').glob('*.py'):
        copy(path, addin_out / 'apper' / 'apper' / path.name)

    shutil.copytree(str(EGG_INFO), str(stage / 'Project_Archiver.egg-info'))

    # PKG-INFO is generated by setuptools in an sdist; recreate it from the
    # egg-info headers plus the current README so the archive is self-describing.
    egg = (EGG_INFO / 'PKG-INFO').read_text(encoding='utf-8')
    headers = re.split(r'\r?\n\r?\n', egg, maxsplit=1)[0]
    headers = re.sub(r'^Version: .*$', 'Version: {}'.format(version), headers, flags=re.MULTILINE)
    pkg_info = headers + '\n\n' + (REPO / 'README.md').read_text(encoding='utf-8')

    (stage / 'PKG-INFO').write_text(pkg_info, encoding='utf-8', newline='\n')
    (stage / 'Project_Archiver.egg-info' / 'PKG-INFO').write_text(
        pkg_info, encoding='utf-8', newline='\n')
    (stage / 'setup.cfg').write_text(
        '[egg_info]\ntag_build = \ntag_date = 0\n', encoding='utf-8', newline='\n')


def write_zip(stage_root, zip_path):
    with zipfile.ZipFile(str(zip_path), 'w', zipfile.ZIP_DEFLATED) as archive:
        for path in sorted(stage_root.rglob('*')):
            archive.write(str(path), path.relative_to(stage_root).as_posix())


def verify(zip_path, version):
    with zipfile.ZipFile(str(zip_path)) as archive:
        names = archive.namelist()
        if archive.testzip() is not None:
            raise SystemExit('error: the created archive is corrupt')

    prefix = 'project_archiver-{}/'.format(version)
    missing = [entry for entry in REQUIRED_ENTRIES if prefix + entry not in names]
    if missing:
        raise SystemExit('error: archive is missing: {}'.format(', '.join(missing)))

    return len(names)


def main():
    parser = argparse.ArgumentParser(description='Build the Project-Archiver release zip.')
    parser.add_argument('--output', type=Path, default=None,
                        help='zip path (default: dist/Project-Archiver-<version>.zip)')
    args = parser.parse_args()

    version = read_version()
    check_sources(version)

    zip_path = args.output or (REPO / 'dist' / 'Project-Archiver-{}.zip'.format(version))
    zip_path = zip_path.resolve()
    zip_path.parent.mkdir(parents=True, exist_ok=True)

    stage_root = Path(tempfile.mkdtemp(prefix='project-archiver-build-'))
    try:
        stage = stage_root / 'project_archiver-{}'.format(version)
        stage.mkdir()
        populate(stage, version)
        if zip_path.exists():
            zip_path.unlink()
        write_zip(stage_root, zip_path)
        entry_count = verify(zip_path, version)
    finally:
        shutil.rmtree(str(stage_root), ignore_errors=True)

    print('built {} ({} files, {:,} bytes)'.format(zip_path, entry_count, zip_path.stat().st_size))
    print('attach it to a release, e.g.:')
    print('  gh release create v{} --title v{} --notes "..." "{}"'.format(
        version, version, zip_path))
    return 0


if __name__ == '__main__':
    sys.exit(main())
